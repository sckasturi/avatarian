#!/usr/bin/env python3
"""
Write wiki/Avatarian_blocks.wiki — every block on one wiki page, for looking at.

The wiki's version of site/blocks.html, without the review tools: three
tables (C-C, V-C, C-V), rows the top glyph, columns the bottom glyph, each
cell one `{{#invoke:Avatarian|render|<top> <bottom>}}`. The cells call the live
Module:Avatarian, so the page redraws itself whenever the module and CSS are
deployed. A block somebody has actually seen written gets a tinted cell with the
words that write it on hover (a {{Script}} underline is lost under the
glyph's box), so the page needs regenerating when a glyph is added or the
corpus grows.

    python3 tools/build_blocks_page.py
    python3 tools/deploy_wiki.py          # uploads it with the module and CSS

Glyph order is the manifest's, the same as the site's blocks page. Cells use
the readable sound codes (sounds.js READABLE), not IPA: on the wiki `j` is the
code for /dʒ/, so IPA /j/ would be misread.
"""

import json
import pathlib
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from build_css_only import glyphs           # noqa: E402
from build_lua_module import SOUNDS, js_object   # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "wiki" / "Avatarian_blocks.wiki"

# Which blocks the corpus writes, and in which words — paired exactly as the
# site's blocks page pairs them (site/js/blockgrid.js `blocksOf`): marks break
# the run, every spelling counts, alternates too. Run through the site's own
# code under the test harness, so the pairing rules are never copied here.
ATTESTED_JS = r"""
const { loadSite } = require(process.argv[1]);
const c = loadSite();
const seen = {};
for (const [word, entry] of Object.entries(c.window.AVATARIAN_CORPUS.words || {})) {
  for (const sp of [entry, ...(entry.alternates || [])]) {
    let run = [];
    const flush = () => {
      for (const { top, bottom } of run.length ? c.resolveBlocks(run) : []) {
        const k = c.parseSymbol(top).sym + "|" + c.parseSymbol(bottom).sym;
        if (!(seen[k] = seen[k] || []).includes(word)) seen[k].push(word);
      }
      run = [];
    };
    for (const t of sp.ipa || []) { if (c.isMark(c.parseSymbol(t).sym)) flush(); else run.push(t); }
    flush();
  }
}
process.stdout.write(JSON.stringify(seen));
"""
SHOW_WORDS = 8   # words named on hover before "and N more"
# Translucent, so it reads on both the light and dark wiki themes.
TINT = "background:rgba(40,150,80,.45)"


def attested():
    harness = str(ROOT / "tests" / "harness.js")
    out = subprocess.run(["node", "-e", ATTESTED_JS, harness], capture_output=True,
                         text=True, check=True, cwd=ROOT).stdout
    return json.loads(out)


def hover(words):
    """The cell's title: the words, alphabetised, at most SHOW_WORDS of them.
    `|`, `=`, braces and quotes would break the cell markup, so they never get in."""
    words = sorted(words, key=str.lower)
    text = ", ".join(words[:SHOW_WORDS])
    if len(words) > SHOW_WORDS:
        text += f" and {len(words) - SHOW_WORDS} more"
    return "".join(ch for ch in text if ch not in "|={}[]\"")


KINDS = [
    ("C–C", "consonant over consonant", "consonant", "consonant"),
    ("V–C", "vowel over consonant", "vowel", "consonant"),
    ("C–V", "consonant over vowel", "consonant", "vowel"),
]


def main():
    code = {ipa: c for c, ipa in js_object(SOUNDS.read_text(encoding="utf-8"), "READABLE")}
    g = glyphs()
    seen = attested()
    drawn = lambda t: [ipa for ipa, e in g.items() if e.get("type") == t and e.get("status") != "PLACEHOLDER"]
    head = lambda ipa: f"{code[ipa]}<br/><small>/{ipa}/</small>"

    out = [
        "<!-- GENERATED by tools/build_blocks_page.py; edits here are overwritten. -->",
        "Every block the script can make, drawn by [[Module:Avatarian]]. "
        "Rows are the '''top''' glyph, columns the '''bottom''' glyph. "
        f'Blocks in a <span style="{TINT}; padding:0 .3em">tinted cell</span> are attested: '
        "hover one for the words that write it. The rest are drawn by rule, not seen.",
        "",
        "__TOC__",
    ]
    for label, desc, top_t, bottom_t in KINDS:
        rows, cols = drawn(top_t), drawn(bottom_t)
        out += ["", f"== {label} ({desc}) ==",
                '{| class="wikitable" style="text-align:center"',
                "! top ↓ bottom →"]
        out += [f"! {head(c)}" for c in cols]
        for r in rows:
            out.append("|-")
            out.append(f"! {head(r)}")
            for c in cols:
                cell = f"{{{{#invoke:Avatarian|render|{code[r]} {code[c]}}}}}"
                words = seen.get(f"{r}|{c}")
                out.append(f'| style="{TINT}" title="{hover(words)}" | {cell}' if words else f"| {cell}")
        out.append("|}")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    n = sum(len(drawn(a)) * len(drawn(b)) for _, _, a, b in KINDS)
    a = sum(1 for _, _, ta, tb in KINDS for r in drawn(ta) for c in drawn(tb) if f"{r}|{c}" in seen)
    print(f"Wrote {OUT} — {n} blocks, {a} attested")


if __name__ == "__main__":
    main()
